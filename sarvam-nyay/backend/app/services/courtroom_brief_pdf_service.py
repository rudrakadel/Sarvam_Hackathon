"""Phase C — reportlab PDF for the VeriDictum Courtroom Audit Brief."""
from __future__ import annotations

import io
import re
from typing import Any, Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak,
)


_INVALID_FILENAME_CHARS = re.compile(r"[^A-Za-z0-9._-]+")


def safe_pdf_filename(seed: str) -> str:
    base = _INVALID_FILENAME_CHARS.sub("-", (seed or "case").strip()).strip("-")
    return f"veridictum-brief-{base[:60] or 'case'}.pdf"


def _styles():
    base = getSampleStyleSheet()
    base.add(ParagraphStyle(name="VdTitle", parent=base["Title"], fontSize=18, leading=22,
                            textColor=colors.HexColor("#1a4d7a")))
    base.add(ParagraphStyle(name="VdSection", parent=base["Heading2"], fontSize=13, leading=16,
                            textColor=colors.HexColor("#1a4d7a"), spaceBefore=12, spaceAfter=4))
    base.add(ParagraphStyle(name="VdBody", parent=base["BodyText"], fontSize=10, leading=14))
    base.add(ParagraphStyle(name="VdQuote", parent=base["BodyText"], fontSize=10, leading=14,
                            leftIndent=12, textColor=colors.HexColor("#555555"), italic=True))
    base.add(ParagraphStyle(name="VdFlag", parent=base["BodyText"], fontSize=10, leading=14,
                            textColor=colors.HexColor("#9c1f1f")))
    return base


def render_courtroom_brief_pdf(
    *,
    case: Dict[str, Any],
    matrix: Dict[str, Any],
    severity_drift: Optional[Dict[str, Any]],
    evidence_gaps: List[Dict[str, Any]],
    low_confidence_critical: List[Dict[str, Any]],
    confirmed_critical_examples: List[Dict[str, Any]],
    talking_points: List[Dict[str, Any]],
    generated_by: str,
) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=letter,
        leftMargin=0.7 * inch, rightMargin=0.7 * inch,
        topMargin=0.7 * inch, bottomMargin=0.7 * inch,
        title="VeriDictum Courtroom Audit Brief", author=generated_by,
    )
    s = _styles()
    story: list = []

    story.append(Paragraph("Courtroom Audit Brief — VeriDictum AI", s["VdTitle"]))
    story.append(Spacer(1, 6))

    meta = [
        ["Case", str(case.get("title") or case.get("case_number") or case.get("id") or "—")],
        ["Status", str(case.get("status") or "—")],
        ["Total contradictions", str(matrix.get("total", 0))],
        ["Confirmed %", f"{matrix.get('confirmed_pct', 0)}%"],
        ["Confirmed critical/high", str(matrix.get("confirmed_critical", 0))],
        ["Unreviewed critical/high", str(matrix.get("ai_suggested_unreviewed_critical", 0))],
        ["Generated by", generated_by],
    ]
    tbl = Table(meta, colWidths=[1.8 * inch, 4.6 * inch])
    tbl.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), "Helvetica", 9),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e6eef5")),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.grey),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.grey),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 10))

    # Severity drift
    story.append(Paragraph("AI Calibration", s["VdSection"]))
    if severity_drift:
        story.append(Paragraph(severity_drift["note"], s["VdFlag"]))
    else:
        story.append(Paragraph("AI calibration is healthy — no significant drift between AI-suggested and attorney-confirmed severity.", s["VdBody"]))

    # Evidence gaps
    story.append(Paragraph("Evidence Gaps", s["VdSection"]))
    if evidence_gaps:
        for g in evidence_gaps:
            story.append(Paragraph(g["note"], s["VdFlag"]))
    else:
        story.append(Paragraph("All evidence indexed and analyzed — no gaps detected.", s["VdBody"]))

    # Low-confidence criticals
    story.append(Paragraph("Low-Confidence Critical/High Findings", s["VdSection"]))
    if low_confidence_critical:
        for lc in low_confidence_critical[:5]:
            story.append(Paragraph(
                f"<b>{lc.get('severity','')}</b> — confidence {lc.get('confidence', 0):.2f}",
                s["VdFlag"],
            ))
            if lc.get("transcript_excerpt"):
                story.append(Paragraph(f"Transcript: &ldquo;{lc['transcript_excerpt']}&rdquo;", s["VdQuote"]))
            if lc.get("document_excerpt"):
                story.append(Paragraph(f"Document: &ldquo;{lc['document_excerpt']}&rdquo;", s["VdQuote"]))
    else:
        story.append(Paragraph("Every critical/high contradiction is above the 0.65 confidence floor.", s["VdBody"]))

    # Contradiction matrix
    story.append(Paragraph("Contradiction Matrix", s["VdSection"]))
    by_status_sev = matrix.get("by_status_severity", {})
    if by_status_sev:
        statuses = sorted(by_status_sev.keys())
        severities = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFORMATIONAL"]
        rows = [["Status"] + severities]
        for st in statuses:
            row = [st]
            for sev in severities:
                row.append(str(by_status_sev.get(st, {}).get(sev, 0)))
            rows.append(row)
        mt = Table(rows, colWidths=[1.5 * inch] + [1.0 * inch] * len(severities))
        mt.setStyle(TableStyle([
            ("FONT", (0, 0), (-1, -1), "Helvetica", 8),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e6eef5")),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e6eef5")),
            ("BOX", (0, 0), (-1, -1), 0.4, colors.grey),
            ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ]))
        story.append(mt)
    else:
        story.append(Paragraph("No contradictions detected for this case.", s["VdBody"]))

    # Confirmed critical examples (top 6)
    if confirmed_critical_examples:
        story.append(PageBreak())
        story.append(Paragraph("Trial-Ready CRITICAL/HIGH Contradictions", s["VdSection"]))
        for ex in confirmed_critical_examples[:6]:
            story.append(Paragraph(
                f"<b>{ex.get('severity','—')}</b> · confidence {ex.get('confidence_score', 0):.2f}",
                s["VdBody"],
            ))
            if ex.get("explanation"):
                story.append(Paragraph(ex["explanation"][:400], s["VdBody"]))
            if ex.get("transcript_text"):
                story.append(Paragraph(f"Transcript: &ldquo;{(ex['transcript_text'] or '')[:200]}&rdquo;", s["VdQuote"]))
            if ex.get("document_text"):
                story.append(Paragraph(f"Document: &ldquo;{(ex['document_text'] or '')[:200]}&rdquo;", s["VdQuote"]))

    # Talking points
    story.append(Paragraph("Attorney Talking Points", s["VdSection"]))
    if talking_points:
        for tp in talking_points:
            story.append(Paragraph(
                f"<b>[{tp.get('topic','general').replace('_',' ')} • {tp.get('severity','info')}]</b> "
                + tp.get("point", ""),
                s["VdBody"],
            ))
    else:
        story.append(Paragraph("No talking points generated.", s["VdBody"]))

    doc.build(story)
    return buf.getvalue()
